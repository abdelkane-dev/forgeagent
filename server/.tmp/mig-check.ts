process.env.DATABASE_URL = 'pglite://memory'
process.env.KEY_PEPPER = 'x'.repeat(40)
process.env.ENCRYPTION_KEY = '0'.repeat(64)
const { runMigrations } = await import('../src/db/migrate')
const { database } = await import('../src/db/client')
await runMigrations()
const r = await database.raw.query(`select count(*)::int as n from pg_policies`)
const t = await database.raw.query(`select relname from pg_class where relrowsecurity and relforcerowsecurity order by 1`)
console.log('policies', (r.rows[0] as {n:number}).n, 'rls tables', t.rows.length)
await database.lockToAppRole()
const who = await database.raw.query(`select current_user`)
const leak = await database.raw.query(`select count(*)::int as n from agents`)
console.log(who.rows, 'agents visible without context:', (leak.rows[0] as {n:number}).n)
await database.close()
